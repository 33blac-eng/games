#!/usr/bin/env bash
# Матриця прогонів під ПОРОГИ RTT з e6b62afd. Кожен рядок — сценарій, який уже
# мав число на СТАРИХ порогах, тож «краще/гірше» видно без інтерпретації.
#
#   ramp15    рампа 15 мс/с   — старе: різало на 60-76 мс. Нове: має різати пізніше.
#   ramp5     рампа 5 мс/с    — старе: НЕ різало взагалі. Нове: має ловити плечем рівня.
#   wobble40  100 мс ±40 мс   — старе: ХИБИЛО (здорове зʼєднання в підлогу). Нове: не має.
#   wobble20  100 мс ±20 мс   — не має хибити (як і раніше).
#   distant   стала 150 мс    — далекий глядач, різати не можна.
#   depth     рампа 25 мс/с   — глибина зрізу: за скільки ціль доходить до підлоги.
#   latch     синусоїда 240 с — засувка плеча рівня: один зріз на епізод і ЗВЕДЕННЯ назад.
#
# wobble40 повторюється 4 рази СВІДОМО: попередній замір мав 1 промах із 4, і це
# частота, а не властивість (див. правило «серія спостережень — не властивість»).
#
# latch: амплітуда 300 мс із періодом 240 с дає максимальний нахил 7.9 мс/с —
# менше за 10 мс/с, потрібні тренду (30 мс за вікно 3 с), тож тренд не спрацює
# НІ РАЗУ і в логу лишиться чисте плече рівня. Приріст піднімається вище 250 мс
# приблизно на 45 с (одна «верхівка»), потім падає під 120 мс — тобто за 520 с
# гарантовано дві верхівки, хоч би з якою фазою почався прогін.
set -u
cd "$(dirname "$0")/.."
R=bench/impair_run.sh

bash $R ramp5     100 -- -delay 300ms  -delay-ramp 60s
bash $R wobble20   60 -- -delay 100ms  -delay-jitter 20ms -delay-jitter-period 4s
bash $R distant    60 -- -delay 150ms
bash $R depth     110 -- -delay 2500ms -delay-ramp 100s
for i in 1 2 3 4; do
  bash $R "wobble40-$i" 90 -- -delay 100ms -delay-jitter 40ms -delay-jitter-period 4s
done
bash $R latch     520 -- -delay 0 -delay-jitter 300ms -delay-jitter-period 240s
echo MATRIX_DONE
