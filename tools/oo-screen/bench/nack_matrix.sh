#!/usr/bin/env bash
# Матриця під NACK_recovered_ratio з ce10a587. Публікатор — КОРПУС (~800 пак/с):
# нерухомий екран сервера дає ~5 пак/с, а вікно судить лише від 16 запитів за 2 с.
#
# ЩО САМЕ РОБИТЬ ЧАСТКУ НИЗЬКОЮ. «Задоволено» = запитаний seq ще в кільці pion на
# 1024 пакети, тобто highest-seq < 1024, де highest — останній seq, який хаб уже
# віддав ЦІЙ нозі. Свіжий дроп у реле завжди в кільці, тож САМІ ПО СОБІ втрати
# частку не валять, хоч 5%, хоч 20%. Валить її ЗАПІЗНЕННЯ запиту: при затримці d
# на нозі hub->viewer глядач бачить дірку на d пізніше, і поки його NACK доїде,
# хаб уже відʼїхав на ~d*pps пакетів уперед. 1024/800 ~ 1.3 с — ось де межа.
# Тому в матриці спершу ЧИСТІ втрати (контроль), потім втрати із затримкою.
set -u
cd "$(dirname "$0")/.."
R=bench/impair_run.sh
export OOS_PUB=corpus

bash $R nack-loss05  45 -- -loss 0.05
bash $R nack-loss20  45 -- -loss 0.20
bash $R nack-d800    45 -- -loss 0.05 -delay 800ms
bash $R nack-d1200   45 -- -loss 0.05 -delay 1200ms
bash $R nack-d1500   60 -- -loss 0.05 -delay 1500ms
bash $R nack-d2500   60 -- -loss 0.05 -delay 2500ms
echo NACK_MATRIX_DONE
