// Адаптація бітрейту (кандидат A). Керує ХАБ, не браузер: hub і так читає RTCP
// Receiver Report із viewer-ноги (той самий sender.Read, що вже тягне PLI), тож
// не треба ані нового DataChannel, ані змін у браузері, і воно працює навіть
// коли вкладку тротлить. Рішення їде агентові ТІЄЇ САМОЇ ноди через уже наявний
// control-канал "oosc-ctl" — повідомленням control.TypeBitrateTarget, одразу за
// ним keyframe_request (нова ціль без свіжого IDR проявилась би аж на
// наступному природному IDR — у нас GOP 2с).
//
// ponytail: стеля цього рішення — частота RTCP. RR приходить раз на кілька
// секунд, тож на різкому обвалі смуги реакція буде із затримкою в один
// RR-інтервал; проміжні кадри вже поїдуть зі старою ціллю. Швидший сигнал —
// TWCC (transport-wide CC) з оцінювачем смуги в агенті: реакція на масштабі
// RTT, а не RTCP-інтервалу. Свідомо не робимо зараз — це окремий шар у агенті,
// а не 100 рядків у хабі. Апгрейд робиться на місці: підмінити джерело
// lossFrac у onReceiverReport, сам контролер лишається як є.
