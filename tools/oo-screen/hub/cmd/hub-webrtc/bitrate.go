	rttLevelHigh = 250 * time.Millisecond

	// minRTTWindow — за яким вікном береться БАЗА приросту (ковзний мінімум у
	// fanout.go). Ручка стоїть тут, до решти ручок RTT, бо крутять їх разом.
	//
	// ЧОМУ ЦІЛИХ ПʼЯТЬ ХВИЛИН. Головна небезпека — не «повільно», а «швидко»:
	// відпустиш базу швидше за затор, і вона НАЗДОЖЕНЕ чергу, приріст схлопнеться
	// в нуль, і контролер перестане бачити реальний затор. Тобто вада стала б
