	//     треба в довгий бік;
	//   - RR приходить раз на кілька секунд, тож у пʼятихвилинну корзину падають
	//     десятки семплів. Вікно на 10 с (як minRTT у BBR) вмістило б два-три —
	//     це майже те саме, що фільтра немає. BBR такий короткий і може собі
	//     дозволити лише тому, що ProbeRTT сам розвантажує чергу й переміряє
	//     справжній мінімум; у нас такого зонда немає, тож вікно мусить
	//     ПЕРЕЖИВАТИ епізод, а не переміряти його посеред.
	minRTTWindow = 5 * time.Minute

	// rttUpClear — приріст, НИЖЧЕ якого знову дозволено підйом. Заміряна хиба
	// (RESULTS-thresholds.md): приріст ріже вниз, але НЕ тримає. На ramp5 зріз
	// стався на 264 мс, а далі ціль спокійно пішла 6.8 -> 8 Мбіт/с за 42 с, поки
