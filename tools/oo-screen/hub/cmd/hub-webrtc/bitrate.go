	rttExcessMin = 120 * time.Millisecond // приріст нижче цього — шум, не затор
	rttRiseStep  = 30 * time.Millisecond  // приріст за вікно, який рахуємо ростом
	rttWindow    = 3 * time.Second        // як часто зсувається точка відліку тренду
	rttSaneMax   = 2 * time.Second        // RTT вище — сміття з мережі, викидаємо

