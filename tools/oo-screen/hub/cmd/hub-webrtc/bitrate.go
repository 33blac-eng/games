	//
	// ЧОМУ 150 мс, А НЕ САМ ПОРІГ ЗРІЗУ. Пускати підйом рівно там, де перестає
	// різати, — це пилка: ціль піднялась, черга від того підросла, зріз повторився.
	// Тому звільнення стоїть ПОМІТНО нижче за те, чим різали (плече рівня 250 мс),
	// із зазором 100 мс — 40% від порога зрізу. Заміряно, що після зрізу приріст
