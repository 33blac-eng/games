	//   - найдовший ЗАМІРЯНИЙ епізод цього контролера — повільна рампа 5 мс/с до
	//     ~300 мс, тобто близько 60 с. Пʼять хвилин — пʼятикратний запас, а з
	//     двома корзинами фактичне вікно 5-10 хв, тож черга мусила б триматись
