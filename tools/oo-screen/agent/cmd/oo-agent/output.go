// Вибір монітора: чиста логіка перемикання виходу, без DXGI й без MFT — тому
// без build-тега windows, і тому перевіряється тестом на машині з ОДНИМ
// монітором (і на Linux-CI). Сам перехід — stream.SwitchOutput у main.go.
package main

import (
	"fmt"
	"sync/atomic"
	"time"
)

// configEpoch — епоха геометрії потоку, та сама, що їде в envelope.ConfigEpoch.
//
// 🚨 Пастка, яку це закриває: раніше тут стояла КОНСТАНТА configEpoch1 = 1, і
// епоха не мінялась ніколи. Перемикання монітора міняє роздільність, тобто
// SPS/PPS: глядач, який не побачив зсуву епохи, дістав би нову геометрію
// посеред старого потоку і зламав би декодер. Тепер кожен успішний
// SwitchOutput її зсуває.
//
// Тримаємо в uint32, бо atomic.Uint16 не існує; у envelope поле 16-бітне, тож
// bumpEpoch сам загортає діапазон і оминає 0 («не задано» на боці глядача).
var configEpoch atomic.Uint32

func init() { configEpoch.Store(1) }

// bumpEpoch зсуває епоху й повертає нову. CAS, а не Add: після 0xFFFF треба
// стрибнути на 1, а не на 0.
func bumpEpoch() uint16 {
	for {
		old := configEpoch.Load()
		next := old + 1
		if next > 0xFFFF {
			next = 1
		}
		if configEpoch.CompareAndSwap(old, next) {
			return uint16(next)
		}
	}
}

// currentEpoch — епоха, з якою зараз маркуються кадри.
func currentEpoch() uint16 { return uint16(configEpoch.Load()) }

// resolveOutput перевіряє індекс монітора, що прийшов ЗЗОВНІ (консоль,
// control-канал), проти реальної кількості виходів.
//
// Свідомо НЕ кламп: якщо просять монітор 3, а їх два, показати замість нього
// монітор 0 — це мовчазна підміна екрана, за яким людина спостерігає, і
// консоль ніколи не дізнається, що її список застарів. На старті правило
// протилежне — див. clampStartOutput.
func resolveOutput(idx, count int) error {
	if count <= 0 {
		return fmt.Errorf("немає жодного DXGI-виходу (count=%d)", count)
	}
	if idx < 0 || idx >= count {
		return fmt.Errorf("виходу %d не існує: на цьому ПК їх %d (0..%d)", idx, count, count-1)
	}
	return nil
}

// clampStartOutput — той самий індекс, але на СТАРТІ: тут кламп правильний.
// Агент піднімають планувальником на ПК працівника з індексом, збереженим
// колись; від'єднали другий монітор — і без клампа агент просто впав би на
// capture.New, тобто ПК зник би з пульта зовсім. Показати основний монітор
// замість неіснуючого краще, ніж не показати нічого; у лог іде рядок про
// підміну, щоб це не виглядало як «прапорець не спрацював».
func clampStartOutput(idx, count int) int {
	if count <= 0 {
		return 0 // енумерація не вдалась — хай пробує capture.New і скаржиться сам
	}
	if idx < 0 || idx >= count {
		return 0
	}
	return idx
}

// encodeGeometry — у якій геометрії кодувати кадри з джерела srcW×srcH.
//
// 🚨 Пастка, яку це закриває: софтверний MFT НЕ масштабує — oos_enc_submit_cpu
// копіює рівно width×height рядків із native-буфера (mft.c). Різниця
// output≠native там означає кроп (native більший) або читання за межі буфера
// (native менший; encode.checkPlanes ловить це як помилку на КОЖНОМУ кадрі —
// потік просто стає). Тому на софт-шляху кодуємо строго в native-розмірі.
// Апаратний шлях масштабує NV12->NV12 через VideoProcessor і бере запитану
// геометрію як є.
//
// Правило було вшите в стартовий код одноразово; винесене сюди, бо
// SwitchOutput приходить у ту саму пастку з іншого боку — новий монітор має
// іншу native-геометрію, ніж той, під який енкодер відкривали.
func encodeGeometry(reqW, reqH, srcW, srcH int, software bool) (int, int) {
	if software {
		return srcW, srcH
	}
	return reqW, reqH
}

// validateSize — A-41: недосказаний запит геометрії має падати на СТАРТІ, а не
// зникати всередині requestedSize.
//
// 🚨 Пастка, яку це закриває: -width=1280 без -height requestedSize мовчки
// відкидав і кодував у рідній. Оператор, який притискає геометрію на слабкому
// каналі, отримував рівно протилежне тому, що просив, і жодного слова про це —
// ані в лозі, ані на екрані. Помилка при старті коштує одного перезапуску;
// мовчазне ігнорування коштує вечора замірів «чому канал не полегшав».
//
// Нуль (типове значення) — не «недосказано», а «рідна роздільність»: він
// проходить. Не проходять «одна вісь із двох» і від'ємні числа.
func validateSize(reqW, reqH int) error {
	if reqW < 0 || reqH < 0 {
		return fmt.Errorf("-width/-height не можуть бути відʼємними: маємо -width=%d -height=%d", reqW, reqH)
	}
	if (reqW > 0) != (reqH > 0) {
		return fmt.Errorf("-width і -height задаються лише разом: маємо -width=%d -height=%d (0 = рідна роздільність виводу)", reqW, reqH)
	}
	return nil
}

// requestedSize — геометрія, яку просимо в енкодера, з прапорців -width/-height
// проти рідного розміру виводу srcW×srcH.
//
// 🚨 Пастка, яку це закриває: типові значення прапорців були зашиті 1920x1080, і
// на моніторі 2560x1440 (Editor, заміряно 30.08) енкодер масштабував униз —
// video.videoWidth×videoHeight у браузері давав 1920x1080 там, де MeshCentral
// віддавав повні 2560x1440. Для роботи з таблицями чіткість важить більше за
// кадри, тож типово кодуємо в рідній.
//
// Нуль (типове значення прапорця) = «рідна». Половина розміру розміром не є:
// заданий лише -width без -height — це не 1000x«скільки вийде», а недосказаний
// запит, і брати з нього одну вісь означало б розтягнути картинку. Тому обидві
// осі мають бути задані, інакше беремо рідну цілком.
func requestedSize(reqW, reqH, srcW, srcH int) (int, int) {
	if reqW <= 0 || reqH <= 0 {
		return srcW, srcH
	}
	return reqW, reqH
}

// fallbackW/fallbackH — геометрія, на яку відступаємо, коли енкодер відмовився
// відкритись у рідній роздільності виводу.
//
// 🚨 Пастка, заміряна 30.08 на цьому ж боксі: «NVIDIA H.264 Encoder MFT» бере
// 1920x1088 і відмовляє MF_E_TRANSFORM_STREAM_INVALID_RESOLUTION (0xC00D6D76)
// вже на 1920x1200 — на ВСІХ рівнях ladder-а (42/50/51/52/MFT's choice) і
// однаково для явного прапорця й автовизначення. Тобто «кодуй у рідній» на
// такій машині без відступу означало б log.Fatalf на encode.New, тобто ПК, який
// зник із пульта — рівно та біда, від якої страхує clampStartOutput.
//
// 1920x1080 не з голови: рівно з цим числом агент їздив на всьому флоті до цієї
// зміни, тож це єдина геометрія, про яку ми ТОЧНО знаємо, що MFT її бере.
const (
	fallbackW = 1920
	fallbackH = 1080
)

// fallbackSize каже, чи є куди відступати після відмови енкодера, і куди саме.
//
// Відступ лише для АВТОвизначеної геометрії: явні -width/-height — це свідомий
// запит оператора, і тиха підміна ховала б від нього те, що машина його не
// тягне. Другого кола теж немає: якщо вже й 1920x1080 не відкрився, справа не в
// роздільності, і помилку треба показати як є.
func fallbackSize(auto bool, w, h int) (int, int, bool) {
	if !auto || (w == fallbackW && h == fallbackH) {
		return w, h, false
	}
	return fallbackW, fallbackH, true
}

// baselineBitrateBps/baselinePixels — щільність потоку, яка вже їздила на проді:
// 8 Мбіт/с на 1920x1080. Це 8_000_000/2_073_600 ≈ 3.86 біт на піксель за
// секунду, і саме її ми зберігаємо як орієнтир.
const (
	baselineBitrateBps = 8_000_000
	baselinePixels     = 1920 * 1080
)

// defaultBitrate — CBR-ціль на старті: явний -bitrate, якщо заданий (шлях для
// слабкого каналу), інакше базова щільність, помножена на РЕАЛЬНІ пікселі кадру.
//
// 🚨 Без цього перехід на рідну роздільність програв би вдруге: 2560x1440 —
// 3 686 400 пікселів проти 2 073 600, тобто в 1.78 раза більше при тому самому
// потоці. Той самий 8 Мбіт/с там дає ~2.17 біт/піксель — мильний текст замість
// чіткішого. При збереженій щільності виходить 8_000_000*3_686_400/2_073_600 =
// 14_222_222 біт/с (≈14.2 Мбіт/с), і це ж число їде в offer як стеля для
// регулятора хаба (ceilingBps), який притисне його сам, якщо канал не тягне.
//
// Згори — стеля maxAutoBitrateBps (A-41): 4K без неї дав би ~32 Мбіт/с.
func defaultBitrate(flagBps, w, h int) int {
	if flagBps > 0 {
		return flagBps
	}
	px := int64(w) * int64(h)
	if px <= 0 {
		return baselineBitrateBps // геометрія невідома — краще старе значення, ніж нуль
	}
	bps := int(baselineBitrateBps * px / baselinePixels)
	// A-41: без стелі 4K давав 32 Мбіт/с — більше, ніж є в каналі більшості
	// ПК; регулятор хаба потім тижнями «підіймався» до неї.
	// P0: стелю піднято 16 -> 30 Мбіт/с. 16 різало 4K (8.3 Мпікс) до ~4
	// біт/кпікс — удвічі менше щільності 1080p, текст мильний. Причина A-41
	// («тижнями підіймався») прибрана в хабі: B4 ріже до доставленої швидкості
	// за 1-2 RR, а B5 відновлює мультиплікативно (секунди, не тижні). 30, а не
	// 32: запас під накладні RTP/SRTP у гігабітному LAN, де 4K і живе.
	if bps > maxAutoBitrateBps {
		bps = maxAutoBitrateBps
	}
	return bps
}

// maxAutoBitrateBps — стеля автоматичного бітрейту (явний -bitrate її не має).
const maxAutoBitrateBps = 30_000_000

// outputRequest переносить запит на перемикання з control-горутини в кадровий
// цикл — рівно як bitrateTarget переносить bitrate_target. Причина та сама і
// сильніша: капчер не є thread-safe («It is NOT safe for concurrent use»,
// capture_windows.go), тож міняти його можна ЛИШЕ там, де крутиться NextFrame.
//
// Зберігаємо idx+1, щоб нуль лишався «нема запиту»: вихід 0 — цілком
// законний індекс, і зі звичайним нулем-сентинелом перемикання на основний
// монітор мовчки б губилось.
type outputRequest struct{ pending atomic.Int64 }

// set затирає попередній незастосований запит: у черзі має сенс лише останній.
func (o *outputRequest) set(idx int) { o.pending.Store(int64(idx) + 1) }

// take віддає запит рівно один раз.
func (o *outputRequest) take() (int, bool) {
	v := o.pending.Swap(0)
	if v == 0 {
		return 0, false
	}
	return int(v - 1), true
}

// softwareNativeAffordable — чи можна собі дозволити СОФТВЕРНИЙ енкодер заради
// рідної роздільності, коли апаратний її не бере.
//
// 🔴 Число не з голови, а заміряне 30.08 на цій самій машині, під однаковим
// навантаженням (повноекранна анімація 2560x1440, живий глядач, 30 с):
//
//	апаратний  NVIDIA MFT  1920x1080  0.26 ядра
//	софтверний MFT         2560x1440  3.31 ядра
//
// Різниця у 12.7 раза. На 24-ядерній машині 3.31 — це 14%, дрібниця. На
// звичайному офісному ПК із 4 ядрами ті самі 3.31 ядра означають 83%
// процесора: людина за таким ПК працювати не зможе, та ще й сама сесія, яку
// ми показуємо, почне гальмувати. Тобто «завжди софт» зробило б гірше, ніж
// нечітка картинка.
//
// Поріг 12 логічних ядер тримає кодувальник під ~28% машини. Це компроміс, а
// не істина: кодувальник працює лише ПОКИ хтось дивиться (on-demand гейтинг),
// тож ціна разова і на час сеансу допомоги.
//
// ponytail: одне число, не таблиця під моделі процесорів. Коли з'явиться
// машина, де це не так, — тут буде видно, що правити.
const softwareNativeMinCores = 12

func softwareNativeAffordable(cores int) bool { return cores >= softwareNativeMinCores }

// --- Ціна софтверного енкодера, коли апаратного НЕМАЄ ЗОВСІМ ---
//
// 🔴 Дірка, яку це закриває (виміряно на парку 30.08). softwareNativeAffordable
// вище стоїть ЛИШЕ на гілці помилки encode.New. А коли апаратного H.264 MFT на
// машині немає взагалі, mft.c мовчки бере софтверний MFT УСЕРЕДИНІ того самого
// виклику, без помилки: encode.New повертає успіх, і перевірка ядер не
// виконується жодного разу. У логах ПК Organic і Computer немає ні рядка
// "hardware refused", ні "falling back" — вони одразу дістали software=true.
// ПК Computer (4 логічні ядра, GTX 560 Ti) через це кодує 1920x1200 софтом,
// тобто приблизно половиною машини.
//
// 🚨 Чому лікуємо ЧАСТОТОЮ, а не роздільністю. Знизити геометрію на софт-шляху
// не можна: софтверний MFT не масштабує, а КРОПИТЬ (oos_enc_submit_cpu копіює
// рівно width×height рядків із native-буфера — див. encodeGeometry). 1920x1080
// на екрані 1920x1200 означало б тихо відрізати нижні 120 рядків разом із
// панеллю задач, і глядач ніколи б не дізнався, що дивиться не весь екран.
// Частота ж ріже роботу лінійно і не ховає жодного пікселя — гірша плавність
// замість зниклого вмісту.
const (
	// Замір 30.08, однакові умови: повноекранна анімація, живий глядач, 30 с.
	// Апаратний 1920x1080 коштував 0.26 ядра, софтверний 2560x1440 — 3.31.
	softwareMeasuredCores  = 3.31
	softwareMeasuredPixels = 2560 * 1440
	softwareMeasuredFPS    = 30

	// Нижче цього не опускаємось: сесія допомоги при 10 к/с ще робоча, а далі
	// починається слайд-шоу, у якому людина не встигає за курсором.
	softwareFPSFloor = 10
)

// softwareCoreCost — скільки ядер з'їсть софтверний енкодер на кадрі в px
// пікселів при fps кадрів/с.
//
// Лінійна екстраполяція ОДНОГО заміру — і це оцінка, не замір. Лінійність тут
// не з голови: робота блокового кодера пропорційна кількості макроблоків і
// кількості кадрів. Ціна похибки мала й однобічна — помилившись, ми віддамо
// трохи більше або трохи менше кадрів, а не зламаємо потік.
func softwareCoreCost(px, fps int) float64 {
	return softwareMeasuredCores *
		(float64(px) / softwareMeasuredPixels) *
		(float64(fps) / softwareMeasuredFPS)
}

// softwareAffordable — чи вкладається софтверний енкодер на кадрі px при fps
// кадрах/с у машину з cores логічними ядрами.
//
// Бюджет тут НЕ нове число: це рівно те, що вже зашите в softwareNativeMinCores
// — 3.31 ядра на 12-ядерній машині, тобто ~28%. Тому й записано через ті самі
// дві сталі, а не через переписану частку: дві ручки не мають як роз'їхатись.
//
// Порівняння перехресне, без ділення, НАВМИСНО: на самій межі (рівно той кадр і
// та частота, з яких виведено поріг) обидва боки мусять бути бітово однаковим
// добутком тих самих float64. Через budget := частка*cores межа не сходилась —
// 12 ядер на 2560x1440 вважались непосильними через останній знак мантиси.
func softwareAffordable(cores, px, fps int) bool {
	return softwareCoreCost(px, fps)*softwareNativeMinCores <= softwareMeasuredCores*float64(cores)
}

// softwareFPSCap — стеля частоти для СОФТВЕРНОГО енкодера на машині з cores
// логічними ядрами і кадром у px пікселів. Повертає fps без змін, якщо машина
// й так укладається в бюджет.
//
// Саме тому на ПК Organic (8 ядер, рідні 1920x1080) не міняється нічого: 1.86
// ядра проти бюджету 2.21 — софт там цілком прийнятний. А на Computer (4 ядра,
// 1920x1200) 2.07 ядра проти 1.10 опускає стелю приблизно до 15 к/с.
//
// ponytail: спуск циклом, а не формулою оберненої лінійності. Формула тут
// повторно вносила б ту саму похибку останнього знака, від якої щойно позбувся
// softwareAffordable, а ціна циклу — щонайбільше fps ітерацій множення.
func softwareFPSCap(cores, px, fps int) int {
	if cores <= 0 || px <= 0 || fps <= 0 {
		return fps // нема з чого рахувати — не чіпаємо
	}
	capped := fps
	for capped > softwareFPSFloor && !softwareAffordable(cores, px, capped) {
		capped--
	}
	return capped
}

// softwareFrameGap — той самий бюджет, але в тому вигляді, у якому його
// споживає кадровий цикл: мінімальний проміжок між КОДОВАНИМИ кадрами. Нуль =
// не притискаємо.
func softwareFrameGap(cores, px, fps int) time.Duration {
	capped := softwareFPSCap(cores, px, fps)
	if capped >= fps || capped <= 0 {
		return 0
	}
	return time.Second / time.Duration(capped)
}

// maxFpsGap — C1: стеля кадрів/с від глядача («Швидкість» тулбара, control
// max_fps) у вигляді проміжку між КОДОВАНИМИ кадрами, як softwareFrameGap.
// Нуль = не притискаємо: стелі немає або вона не нижча за власний -fps агента.
// Кадр викидається ДО кодування — референси енкодера цілі, IDR не потрібен.
func maxFpsGap(capFps, encFps int) time.Duration {
	if capFps <= 0 || capFps >= encFps {
		return 0
	}
	return time.Second / time.Duration(capFps)
}
